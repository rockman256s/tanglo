(function (WG) {
  'use strict';

  // Маски-фигуры: '#' — клетка есть, '.' — дыра (лучи проходят, стрелок нет)
  const LIST = [
    { name: 'heart', rows: [
      '.##...##.',
      '####.####',
      '#########',
      '#########',
      '.#######.',
      '..#####..',
      '...###...',
      '....#....',
    ] },
    { name: 'star', rows: [
      '....#....',
      '...###...',
      '#########',
      '.#######.',
      '..#####..',
      '..##.##..',
      '.##...##.',
    ] },
    { name: 'diamond', rows: [
      '....#....',
      '...###...',
      '..#####..',
      '.#######.',
      '#########',
      '.#######.',
      '..#####..',
      '...###...',
      '....#....',
    ] },
    { name: 'cat', rows: [
      '#.......#',
      '###...###',
      '#########',
      '##.#.#.##',
      '#########',
      '.#######.',
      '..#####..',
    ] },
    { name: 'fish', rows: [
      '#....#####.',
      '##..#######',
      '###.#######',
      '##..#######',
      '#....#####.',
    ] },
    { name: 'house', rows: [
      '....#....',
      '...###...',
      '..#####..',
      '.#######.',
      '#########',
      '#.#...#.#',
      '#.#...#.#',
      '#########',
    ] },
    { name: 'tree', rows: [
      '....#....',
      '...###...',
      '..#####..',
      '...###...',
      '..#####..',
      '.#######.',
      '...###...',
      '...###...',
    ] },
    { name: 'smiley', rows: [
      '..#####..',
      '.#######.',
      '##.###.##',
      '#########',
      '#########',
      '#.#...#.#',
      '##.###.##',
      '.#######.',
      '..#####..',
    ] },
  ];

  // Ближайший сосед: растягивает маску до W×H
  function fit(rows, W, H) {
    const h = rows.length;
    const w = rows[0].length;
    const out = [];
    for (let y = 0; y < H; y++) {
      const sy = Math.floor((y + 0.5) * h / H);
      let line = '';
      for (let x = 0; x < W; x++) {
        const sx = Math.floor((x + 0.5) * w / W);
        line += rows[sy][sx];
      }
      out.push(line);
    }
    return out;
  }

  // Фигура по индексу (по кругу), растянутая до W×H
  function get(index, W, H) {
    const shape = LIST[((index % LIST.length) + LIST.length) % LIST.length];
    return { name: shape.name, mask: fit(shape.rows, W, H) };
  }

  WG.shapes = { list: LIST, count: LIST.length, fit, get };

})(window.WG = window.WG || {});
